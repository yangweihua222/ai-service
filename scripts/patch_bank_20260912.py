def main():
    text = BANK.read_text(encoding="utf-8")
    before = len(text.splitlines())

    for anchor, block, tag in (
        (ANCHOR_15, BLOCK_15, "1.5 Token 预算 P0"),
        (ANCHOR_210, BLOCK_210, "2.10 再决策提示词"),
    ):
        if block in text:
            print(f"[跳过] {tag} 已存在")
            continue
        if anchor not in text:
            print(f"[错误] {tag} 锚点未找到，请手工检查")
            raise SystemExit(1)
        text = text.replace(anchor, block, 1)
        print(f"[已插入] {tag}")

    BANK.write_text(text, encoding="utf-8")
    after = len(text.splitlines())
    print(f"行数：{before} -> {after}")
    _quality_check(text)


def _quality_check(text: str):
    print("\n=== 质量检查 ===")
    # 表格列数一致性（同一表格内分隔行列数需与表头一致）
    bad = 0
    header_cells = None
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("|") and s.endswith("|"):
            n = s.count("|") - 1
            if set(s.replace("|", "").replace(":", "").replace("-", "").strip()) == set():
                continue
            if header_cells is None:
                header_cells = n
            elif n != header_cells:
                bad += 1
        else:
            header_cells = None
    print(f"表格列数不一致的行：{bad}")
    print("含 HTML 锚点：", "<a " in text or 'id="' in text)
    print("新增标记数：", text.count("2026-09-12 实测补记"))


if __name__ == "__main__":
    main()

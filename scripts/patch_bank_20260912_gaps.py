def main():
    text = BANK.read_text(encoding="utf-8")
    before = len(text.splitlines())

    # G 和 H 都插在 6.5 末尾：先拼成一大块再插一次，避免锚点被消耗
    g_block = render("测试与发布", 8, BLOCKS[6][3])
    h_block = render("运维部署", 5, BLOCKS[7][3])

    for anchor, domain, n, rows in BLOCKS[:6]:
        block = render(domain, n, rows)
        if anchor is None:
            continue
        if block in text:
            print(f"[跳过] {domain} 已存在")
            continue
        if anchor not in text:
            print(f"[错误] {domain} 锚点未找到")
            raise SystemExit(1)
        text = text.replace(anchor, block + anchor, 1)
        print(f"[已插入] {domain}（{n} 项）")

    # G+H 插在 6.5 章节末尾（即文末"验证结论"之前或章节结束处）
    tail_anchor = "## 6.5 Docker 部署怎么做的？"
    if g_block not in text:
        if tail_anchor not in text:
            print("[错误] 6.5 锚点未找到")
            raise SystemExit(1)
        # 找 6.5 章节的结束位置：下一个 "## " 标题或文件末尾
        idx = text.index(tail_anchor)
        nxt = text.find("\n## ", idx + len(tail_anchor))
        # 6.5 之后是附录，找 "验证结论" 之前
        end = text.find("验证结论：", idx)
        if end == -1:
            end = len(text)
        # 回退到该行开头
        end = text.rfind("\n", idx, end) + 1
        text = text[:end] + g_block + h_block + text[end:]
        print("[已插入] 测试与发布（8 项）+ 运维部署（5 项）")

    BANK.write_text(text, encoding="utf-8")
    after = len(text.splitlines())
    print(f"\n行数：{before} -> {after}")

    # 质量检查
    bad = 0
    hdr = None
    for i, l in enumerate(text.splitlines(), 1):
        s = l.strip()
        if s.startswith("|") and s.endswith("|"):
            cnt = s.count("|") - 1
            if set(s.replace("|", "").replace(":", "").replace("-", "").strip()) == set():
                continue
            if hdr is None:
                hdr = cnt
            elif cnt != hdr:
                bad += 1
                if bad <= 5:
                    print(f"  列数不一致 行{i}: {cnt} vs {hdr} | {s[:50]}")
        else:
            hdr = None
    print("表格列数不一致：", bad)
    print("生产差距对照表数：", text.count("生产差距对照表"))


if __name__ == "__main__":
    main()
